#!/usr/bin/env python3
"""Derive delivery counts and audit queues without promoting evidence status."""

from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import tomllib

from check_federated_knowledge import validate_committed

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "generated/delivery-inventory.json"
MARKDOWN = ROOT / "generated/delivery-inventory.md"


def render() -> tuple[str, str]:
    paths = ["claims/claims.toml", "knowledge/psk.toml", "llm/misconceptions.toml",
             "generated/federated-knowledge-pair-manifest.json"]
    claims = tomllib.loads((ROOT / paths[0]).read_text())["claim"]
    knowledge = tomllib.loads((ROOT / paths[1]).read_text())["knowledge"]
    misconceptions = tomllib.loads((ROOT / paths[2]).read_text())["misconception"]
    for items, key in ((claims, "claim_id"), (knowledge, "id"), (misconceptions, "id")):
        if len({item[key] for item in items}) != len(items):
            raise ValueError(f"inventory source has duplicate {key} identities")
    pair = json.loads((ROOT / paths[3]).read_text())
    errors = validate_committed(pair)
    if errors:
        raise ValueError("inventory requires a valid pair: " + "; ".join(errors))
    links = {item["id"]: [] for item in misconceptions}
    for item in knowledge:
        for misconception in item["book"]["misconception_ids"]:
            if misconception not in links:
                raise ValueError(f"unknown misconception backlink: {misconception}")
            links[misconception].append(item["id"])
    unlinked = sorted(key for key, values in links.items() if not values)
    uncited = sorted(item["claim_id"] for item in claims
                     if item["status"] == "established_result" and not item.get("citation_keys"))
    verification_counts = Counter(item["verification"] for item in claims)
    verification_counts.setdefault("externally-reviewed", 0)
    verification = dict(sorted(verification_counts.items()))
    package = pair["bmopftools"]
    inventory = {
        "schema_version": "1.0.0",
        "source_sha256": {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in paths},
        "pair_sha256": pair["pair_sha256"],
        "claims": {"total": len(claims), "verification": verification,
                   "established_without_citation_keys": uncited},
        "knowledge": {"total": len(knowledge), "execution_status": dict(sorted(Counter(
            item["executable"]["implementation_status"] for item in knowledge).items()))},
        "misconceptions": {"total": len(misconceptions), "psk_linked": len(links) - len(unlinked),
                           "psk_links": {key: sorted(values) for key, values in sorted(links.items())}, "unlinked_ids": unlinked},
        "bmopftools": {"revision": package["revision"], "finding_registry": package["finding_registry"],
                       "executable_export_record_counts": package["record_counts"]},
    }
    lines = ["# Generated delivery inventory", "",
             "Generated by `scripts/generate_delivery_inventory.py`; edit the canonical registries, not this file.", "",
             "These are registry counts and audit queues, not newly measured scientific results.", "",
             "| Inventory | Count |", "|---|---:|",
             f"| Claims | {len(claims)} |",
             *[f"| Claim verification: `{state}` | {count} |" for state, count in verification.items()],
             f"| PSK records | {len(knowledge)} |",
             f"| Stable misconception IDs | {len(links)} |",
             f"| Misconception IDs with a PSK link | {len(links) - len(unlinked)} |",
             f"| Misconception IDs without a PSK link | {len(unlinked)} |",
             f"| Full pinned package Finding registry | {package['finding_registry']['finding_count']} |",
             f"| Finding records in the curated executable export | {package['record_counts']['finding']} |",
             "", "The full Finding catalogue and the curated executable export have different scopes.",
             "A PSK link alone establishes neither an executable implementation nor independent review.",
             "Self-checks and independent implementations retain their distinct ledger states.", "",
             "## Misconception IDs still requiring a PSK link or explicit exclusion", "",
             *[f"- `{key}`" for key in unlinked], "",
             "## Established-result entries without citation keys", "",
             f"There are {len(uncited)} entries in this audit queue. Missing citation keys do not show that",
             "a statement is false or necessarily requires an external citation. Review each entry's",
             "basis: cited result, explicit book derivation, or bounded numerical evidence. Do not",
             "promote a finite numerical test into a general theorem through a status label.", "",
             *[f"- `{key}`" for key in uncited], "",
             "## Pinned source identity", "",
             f"- BMOPFTools revision: `{package['revision']}`",
             f"- Finding registry SHA-256: `{package['finding_registry']['sha256']}`",
             f"- Federated pair SHA-256: `{pair['pair_sha256']}`",
             "- [Machine-readable inventory and source hashes](delivery-inventory.json)", ""]
    return json.dumps(inventory, indent=2, sort_keys=True) + "\n", "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payloads = render()
    for path, payload in zip((OUTPUT, MARKDOWN), payloads):
        if args.write:
            path.write_text(payload)
        elif not path.is_file() or path.read_text() != payload:
            print(f"stale delivery inventory: {path.relative_to(ROOT)}; run with --write")
            return 1
    print("Delivery inventory matches canonical claims, PSK/misconception registries and pinned package counts.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
